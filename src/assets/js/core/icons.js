function lucideSvg(name, size = 16) {
  const body = LUCIDE_ICONS[name];
  if (!body) throw new Error(`Unknown icon: ${name}`);
  return `<svg class="lucide" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

/* Replaces every <i data-icon="name"> placeholder under `root` with its SVG. */
function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((slot) => {
    const template = document.createElement('template');
    template.innerHTML = lucideSvg(slot.dataset.icon, Number(slot.dataset.size) || 16);
    const svg = template.content.firstElementChild;
    if (slot.className) svg.classList.add(...slot.className.split(/\s+/).filter(Boolean));
    slot.replaceWith(svg);
  });
}

